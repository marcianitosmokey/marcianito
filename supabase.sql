create table if not exists public.guestbook (
  id bigint generated by default as identity primary key,
  name text not null default 'Visitante anónimo' check (char_length(name) <= 32),
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now()
);
alter table public.guestbook enable row level security;
drop policy if exists "Anyone can read guestbook" on public.guestbook;
create policy "Anyone can read guestbook" on public.guestbook for select using (true);
drop policy if exists "Anyone can leave a guestbook message" on public.guestbook;
create policy "Anyone can leave a guestbook message" on public.guestbook for insert with check (
  char_length(message) between 1 and 500 and char_length(name) <= 32
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 90),
  body text not null check (char_length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);
alter table public.posts enable row level security;
drop policy if exists "Anyone can read posts" on public.posts;
create policy "Anyone can read posts" on public.posts for select using (true);
drop policy if exists "Authenticated users can publish posts" on public.posts;
-- Reemplaza TU_CORREO@EJEMPLO.COM por el correo que usarás para administrar la página.
create policy "Only site owner can publish posts" on public.posts for insert to authenticated
with check ((auth.jwt() ->> 'email') = 'TU_CORREO@EJEMPLO.COM');

